#Requires -Version 5.1
<#
.SYNOPSIS
    Create a .venv inside the KiCad plugin directory, install kcaa, and
    download the freerouting JAR for the auto-router feature.

.DESCRIPTION
    Run this script from inside the kicad_ai_assistant plugin folder, e.g.:

        cd "$env:APPDATA\kicad\10.0\scripting\plugins\kicad_ai_assistant"
        .\setup_plugin.ps1                            # kcaa from PyPI
        .\setup_plugin.ps1 C:\path\to\kcaa-build      # local build

    Without a path the released kcaa==<VERSION> is installed from PyPI and the
    VERSION file is required. With a path, that build is installed instead and
    no VERSION file is needed: a directory is installed editable, any other
    path is passed to uv as an artifact.
#>

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$KcaaPath
)

$ErrorActionPreference = 'Stop'

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------
$PythonVersion     = '3.13'
$FreroutingVersion = '2.2.3'
$JarName           = "freerouting-${FreroutingVersion}.jar"
$DownloadUrl       = "https://github.com/freerouting/freerouting/releases/download/v${FreroutingVersion}/${JarName}"

# $PSScriptRoot is the directory containing this script (the plugin folder).
$PluginDir = $PSScriptRoot
$VenvDir   = Join-Path $PluginDir '.venv'

# ---------------------------------------------------------------------------
# Parse the optional local path
# ---------------------------------------------------------------------------
$HasLocalPath = $false
$LocalPath    = $null
$SourceKind   = 'pypi'

if ($PSBoundParameters.ContainsKey('KcaaPath')) {
    if ([string]::IsNullOrWhiteSpace($KcaaPath)) {
        Write-Host 'ERROR: empty path argument'
        Write-Host 'Pass a path to a build, or no argument to install from PyPI.'
        exit 2
    }
    if (-not (Test-Path -LiteralPath $KcaaPath)) {
        Write-Host "ERROR: local path does not exist: $KcaaPath"
        exit 1
    }
    $ResolvedPath = Resolve-Path -LiteralPath $KcaaPath
    $LocalPath    = $ResolvedPath.ProviderPath
    $HasLocalPath = $true
    if (Test-Path -LiteralPath $LocalPath -PathType Leaf) {
        $SourceKind = 'local path'
    } else {
        $SourceKind = 'source directory'
    }
}

# ---------------------------------------------------------------------------
# Determine the kcaa source. The VERSION file is only required for the PyPI
# path, so a local build works without one.
# ---------------------------------------------------------------------------
$KcaaVersion = $null
if ($HasLocalPath) {
    Write-Host "kcaa source: $SourceKind $LocalPath"
} else {
    $VersionFile = Join-Path $PluginDir 'VERSION'
    if (-not (Test-Path -LiteralPath $VersionFile)) {
        Write-Host "ERROR: VERSION file not found at $VersionFile"
        Write-Host "The VERSION file is generated by 'make dist-plugin' from pyproject.toml."
        Write-Host 'Pass a local path to install a build without it.'
        exit 1
    }
    $KcaaVersion = (Get-Content -LiteralPath $VersionFile -Raw).Trim()
    Write-Host "kcaa source: PyPI kcaa==${KcaaVersion} (VERSION file)"
}

# ---------------------------------------------------------------------------
# Sanity checks
# ---------------------------------------------------------------------------
if (-not (Get-Command 'uv' -ErrorAction SilentlyContinue)) {
    Write-Host "ERROR: uv not found in PATH. Install it from https://github.com/astral-sh/uv"
    exit 1
}

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
Write-Host "Plugin dir : $PluginDir"
Write-Host "Venv dir   : $VenvDir"
Write-Host ""

# ---------------------------------------------------------------------------
# Step 1/3 — Create / update the venv
# ---------------------------------------------------------------------------
Write-Host "Step 1/3 - Creating virtual environment ..."
# --allow-existing: reuse an existing .venv instead of aborting. Current uv
# refuses an existing target ("Use --clear to replace it"), so without this
# flag a re-run could never reinstall over an installed build.
uv venv "$VenvDir" --python $PythonVersion --allow-existing
if ($LASTEXITCODE -ne 0) {
    Write-Host "ERROR: uv venv failed (exit code $LASTEXITCODE)."
    exit $LASTEXITCODE
}

# ---------------------------------------------------------------------------
# Step 2/3 — Install kcaa
# ---------------------------------------------------------------------------
Write-Host "Step 2/3 - Installing kcaa ($SourceKind) ..."
if ($HasLocalPath) {
    # --reinstall-package kcaa: an installed equal version must be replaced,
    # without uninstalling and reinstalling every other package in the venv.
    if ($SourceKind -eq 'source directory') {
        uv pip install -e "$LocalPath" --reinstall-package kcaa --python "$VenvDir"
    } else {
        uv pip install "$LocalPath" --reinstall-package kcaa --python "$VenvDir"
    }
} else {
    uv pip install "kcaa==${KcaaVersion}" --python "$VenvDir"
}
uv pip install "pymupdf" --python "$VenvDir"
if ($LASTEXITCODE -ne 0) {
    Write-Host "ERROR: uv pip install failed (exit code $LASTEXITCODE)."
    exit $LASTEXITCODE
}

# ---------------------------------------------------------------------------
# Installed module — metadata only, importing kcaa needs a KiCad environment
# ---------------------------------------------------------------------------
Write-Host "Installed kcaa:"
$ProbeScript = @'
import json
from importlib.metadata import distribution
from urllib.parse import unquote, urlparse

dist = distribution("kcaa")
info = "{} at {}".format(dist.version, dist.locate_file(""))
raw = dist.read_text("direct_url.json")
try:
    direct = json.loads(raw) if raw else {}
except ValueError:
    direct = {}
if direct.get("dir_info", {}).get("editable") and direct.get("url"):
    info += " (editable source: {})".format(unquote(urlparse(direct["url"]).path))
print(info)
'@

$PythonExe = Join-Path $VenvDir 'Scripts\python.exe'
$PreviousEap = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
Push-Location -LiteralPath $VenvDir
try {
    $KcaaInfo = (& $PythonExe -c $ProbeScript 2>&1 | Out-String).Trim()
    $ProbeExit = $LASTEXITCODE
} finally {
    Pop-Location
    $ErrorActionPreference = $PreviousEap
}
if ($ProbeExit -eq 0) {
    Write-Host "  $KcaaInfo"
} else {
    Write-Host "  WARNING: could not read kcaa metadata from $VenvDir"
    foreach ($Line in $KcaaInfo.Split("`n")) {
        Write-Host "    $Line"
    }
}

# ---------------------------------------------------------------------------
# Step 3/4 — Detect KiCad configuration
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "Step 3/3 - Downloading freerouting JAR ..."
$JarDest = Join-Path $PluginDir $JarName

if (Test-Path $JarDest) {
    Write-Host "  Already present: $JarDest (skipping download)"
} else {
    Write-Host "  URL: $DownloadUrl"
    try {
        Invoke-WebRequest -Uri $DownloadUrl -OutFile $JarDest -UseBasicParsing
        Write-Host "  Saved to: $JarDest"
    } catch {
        Write-Host "ERROR: Failed to download freerouting JAR: $_"
        exit 1
    }
}

# ---------------------------------------------------------------------------
# Done
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "Done! The plugin venv is ready at:"
Write-Host "  $(Join-Path $VenvDir 'Scripts\python.exe')"
Write-Host ""
Write-Host "Restart KiCad (or reload the plugin) for the changes to take effect."

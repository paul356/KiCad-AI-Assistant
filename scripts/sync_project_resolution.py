#!/usr/bin/env python3
"""Synchronise the vendored plugin copy of the project resolver.

The KiCad plugin runs inside KiCad's embedded Python and cannot import the
``kcaa`` package, so it ships an independent copy of
``kcaa/utils/project_resolution.py``.  That copy is generated byte-for-byte
from the core module; never edit it by hand.

Usage:
    python scripts/sync_project_resolution.py
    python scripts/sync_project_resolution.py --check
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "kcaa" / "utils" / "project_resolution.py"
TARGET = REPO_ROOT / "kicad_plugin" / "project_resolution.py"


def check() -> bool:
    """Return True when the vendored copy matches the core module exactly."""
    if not TARGET.is_file():
        return False
    return TARGET.read_bytes() == SOURCE.read_bytes()


def sync() -> None:
    """Write the core module to the vendored plugin path byte-for-byte."""
    TARGET.write_bytes(SOURCE.read_bytes())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="only compare the vendored copy and return non-zero on drift",
    )
    args = parser.parse_args(argv)

    if args.check:
        if check():
            print(f"{TARGET.name} is up to date")
            return 0
        print(
            f"{TARGET.name} is out of date; run python scripts/sync_project_resolution.py",
            file=sys.stderr,
        )
        return 1

    sync()
    print(f"Wrote {TARGET.name} from {SOURCE.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
